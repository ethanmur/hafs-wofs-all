"""Write one case YAML per WoFS deployment from the A1 inventory tables.

    python analysis/make_case_yamls.py wofs_inventory.csv wofs_windows.csv \
        [--out-dir storms]

The scoring window of a deployment is not typed in: it runs from the start of
its first complete 3 h window to the end of its last, read from the window
availability table written by wofs_inventory.py. A deployment with no complete
window (Idalia as downloaded) still gets a file, marked ``available: false``,
so it appears in every later table instead of silently vanishing.

HAFS members are the cycles of one configuration initialized at most
``lookback_h`` hours before a window starts (and strictly before it): 6-hourly
cycles over 48 h are 8 per configuration, 16 with HFSA and HFSB kept as
separate models. A window needs ``min_members`` of them, the two configurations
counted together, to be HAFS-eligible.
"""

import argparse
import csv
import sys
from datetime import datetime, timedelta
from pathlib import Path

ORION = "/work2/noaa/aoml-hafs1/emurray/ppgc-hafs"
TIME_FMT = "%Y-%m-%d %H%MZ"
HAFS_CYCLE_H = 6
HAFS_LOOKBACK_H = 48
HAFS_MIN_MEMBERS = 8
HAFS_MODELS = ("HFSA", "HFSB")

# WoFS archive folder -> (HAFS storm id, display name, b-deck file)
STORMS = {
    "2023_HILARY": ("2023-09e", "Hilary", "bep092023.dat"),
    "2023_IDALIA": ("2023-10l", "Idalia", "bal102023.dat"),
    "2024_BERYL":  ("2024-02l", "Beryl",  "bal022024.dat"),
    "2024_HELENE": ("2024-09l", "Helene", "bal092024.dat"),
    "2024_MILTON": ("2024-14l", "Milton", "bal142024.dat"),
}


def read_csv(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def parse_time(text):
    return datetime.strptime(text, TIME_FMT)


def floor_to_cycle(dt, cycle_h=HAFS_CYCLE_H):
    """Latest HAFS cycle time at or before dt."""
    return dt.replace(hour=dt.hour - dt.hour % cycle_h, minute=0, second=0,
                      microsecond=0)


def served_span(window_rows):
    """(valid_start, valid_end, n_windows) over the complete windows of one
    deployment, or None if it has none."""
    done = {(r["window_start"], r["window_end"])
            for r in window_rows if r["status"] == "complete"}
    if not done:
        return None
    starts = [parse_time(s) for s, _ in done]
    ends = [parse_time(e) for _, e in done]
    return min(starts), max(ends), len(done)


def build_case(inv_row, window_rows, lookback_h=HAFS_LOOKBACK_H):
    """Dict of everything a case file holds for one deployment."""
    folder = inv_row["storm"]
    storm_id, name, bdeck = STORMS[folder]
    case = {
        "storm_name": name,
        "storm_id": storm_id,
        "year": folder[:4],
        "deployment": inv_row["deployment"],
        "folder": folder,
        "bdeck": bdeck,
        "span": served_span(window_rows),
        "lookback_h": lookback_h,
    }
    if case["span"]:
        start, end, _ = case["span"]
        case["init_start"] = floor_to_cycle(
            start - timedelta(hours=lookback_h))
        case["init_end"] = floor_to_cycle(end)
    return case


def case_filename(case):
    short = case["storm_id"].split("-")[1]
    return (f"{case['year']}_{short}_{case['storm_name'].lower()}_"
            f"{case['deployment']}.yaml")


def _hour(dt):
    return f"{dt:%Y%m%d%H}"


def path_lines(storm_name, deployment, orion=ORION):
    """Where a deployment's files go: by kind, under data/ or figures/ -- never
    a per-case output tree. Grid specs and grid maps are one flat folder each
    (the case is in the file name); regridded obs and their maps get one
    <deployment>_<storm> folder per deployment."""
    return [
        f"grid_json_dir:   {orion}/data/json-grids/",
        f"grid_plot_dir:   {orion}/figures/regrid-wofs/",
        f"regrid_dir:      {orion}/data/stage-iv-regrid/"
        f"{deployment}_{storm_name.lower()}/",
        f"regrid_plot_dir: {orion}/figures/regrid-obs-tests/"
        f"{deployment}_{storm_name.lower()}/",
        f"manifest_dir:    {orion}/data/window-manifests/",
        f"wofs_regrid_dir: {orion}/data/wofs-regrid/"
        f"{deployment}_{storm_name.lower()}/",
        f"mask_dir:        {orion}/data/obs-valid-masks/",
        f"mask_plot_dir:   {orion}/figures/obs-valid-masks/",
        f"log_dir:         {orion}/data/logs/",
        f"mrms_cache_dir:   {orion}/data/mrms/",
        f"stage4_cache_dir: {orion}/data/stage-iv/",
    ]


def render_case(case, orion=ORION):
    sid, dep = case["storm_id"], case["deployment"]
    lines = [
        f"# {case['storm_name']} {case['year']} ({sid}) -- WoFS deployment {dep}",
        "# Generated by analysis/make_case_yamls.py from the A1 inventory",
        "# tables; regenerate rather than editing the scoring window by hand.",
        "",
        f"storm_name: {case['storm_name']}",
        f"storm_id: {sid}",
        f"deployment: {dep}",
        f"best_track: {orion}/data/bdeck/{case['bdeck']}",
        "",
        "# Stage IV by default; mrms switches the truth product.",
        "truth_source: stage4",
        "",
        "wofs:",
        f"  root: {orion}/data/wofs-full/{case['folder']}/{dep}",
    ]
    span = case["span"]
    if span:
        start, end, n = span
        lines += [
            "  available: true",
            f"  complete_windows: {n}",
            "",
            "# Scored period: first complete 3 h window start to last end.",
            f"valid_start: {_hour(start)}",
            f"valid_end:   {_hour(end)}",
            "",
            "# HAFS members for a window: cycles of one configuration initialized",
            "# at most lookback_h before the window start and strictly before it.",
            "# A window is HAFS-eligible with at least min_members members, HFSA",
            "# and HFSB together; below that it is scored as WoFS-only.",
            "hafs:",
            f"  lookback_h: {case['lookback_h']}",
            f"  min_members: {HAFS_MIN_MEMBERS}",
            f"  init_start: {_hour(case['init_start'])}",
            f"  init_end:   {_hour(case['init_end'])}",
            "  models:",
        ] + [f"    {m}: {orion}/data/hafs/{sid}/{m}" for m in HAFS_MODELS]
    else:
        lines += [
            "  available: false   # no complete 3 h window in the archive",
            "  complete_windows: 0",
            "",
            "# No scoring window: nothing complete to verify. Kept so the",
            "# deployment still shows up in every later table.",
        ]
    lines += [""] + path_lines(case["storm_name"], dep, orion) + [""]
    return "\n".join(lines)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("inventory_csv")
    ap.add_argument("windows_csv")
    ap.add_argument("--out-dir", default="storms")
    ap.add_argument("--lookback-h", type=int, default=HAFS_LOOKBACK_H)
    args = ap.parse_args(argv)

    windows = {}
    for r in read_csv(args.windows_csv):
        windows.setdefault((r["storm"], r["deployment"]), []).append(r)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for row in read_csv(args.inventory_csv):
        key = (row["storm"], row["deployment"])
        if row["storm"] not in STORMS:
            print(f"skipping {key}: no storm id mapping in STORMS")
            continue
        case = build_case(row, windows.get(key, []), args.lookback_h)
        path = out_dir / case_filename(case)
        path.write_text(render_case(case))
        state = (f"{case['span'][2]} windows" if case["span"]
                 else "NO COMPLETE WINDOWS")
        print(f"wrote {path}  ({state})")


if __name__ == "__main__":
    main(sys.argv[1:])
